package javasnes.util.types.vars.abstracts.pointer.number.unsigned;

import javasnes.util.types.vars.abstracts.pointer.number.SnesPointerNumber;

/**
 * Represents an abstract class for SNES pointer numbers that are unsigned.
 * 
 * This class extends {@link SnesPointerNumber} and serves as a base for all
 * unsigned number pointer types in the SNES context.
 * 
 */
public abstract class SnesPointerUnsignedNumber extends SnesPointerNumber {

    public SnesPointerUnsignedNumber() {}

}

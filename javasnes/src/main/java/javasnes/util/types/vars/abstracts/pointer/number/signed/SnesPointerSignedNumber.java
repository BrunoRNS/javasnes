package javasnes.util.types.vars.abstracts.pointer.number.signed;

import javasnes.util.types.vars.abstracts.pointer.number.SnesPointerNumber;

/**
 * Represents an abstract class for signed number pointer types in the SNES context.
 * 
 * This class extends {@link SnesPointerNumber} and serves as a base for all signed
 * pointer number implementations. It does not define any additional methods or fields,
 * but provides a common type for signed pointer numbers.
 * 
 */
public abstract class SnesPointerSignedNumber extends SnesPointerNumber {

    public SnesPointerSignedNumber() {}

}
